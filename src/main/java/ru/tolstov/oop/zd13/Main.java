package ru.tolstov.oop.zd13;

/*
В системе есть корзина.
У корзины есть:
список товаров
У каждого товара в корзине есть:
название
цена
количество
Нужно реализовать систему, которая может:
добавить товар в корзину
удалить товар из корзины
изменить количество товара
посчитать общую стоимость корзины
показать содержимое корзины
Правила:
если количество стало 0, товар удаляется из корзины
общая стоимость корзины считается как сумма цена × количество для всех товаров
Пример:
В корзине:
Телефон — 500 × 1
Чехол — 20 × 2
Зарядка — 30 × 1
Общая стоимость:
570
 */
public class Main {
    public static void main(String[] args) {
        ShoppingCart cart = new ShoppingCart();

        Product phone = new Product("Телефон", 500, "SKU1");
        Product cover = new Product("Чехол", 20, "SKU2");

        // 1. Добавляем товары
        cart.addProduct(phone, 1);
        cart.addProduct(cover, 2);

        // 2. Добавляем еще один телефон (проверяем, что количество увеличится, а не появится дубль)
        cart.addProduct(phone, 1);

        System.out.println("--- Корзина после добавлений ---");
        cart.showItems(); // Ожидаем: Телефон 500х2, Чехол 20х2

        // 3. Изменяем количество на 0 (проверяем правило удаления)
        System.out.println("\n--- Удаляем Чехол (меняем количество на 0) ---");
        cart.changeQuantity("Чехол", 0);

        // 4. Итоговый вывод
        System.out.println("\n--- Итоговая корзина ---");
        cart.showItems(); // Ожидаем: Телефон 500х2
        System.out.println("Общая стоимость: " + (int)cart.calculateTotal()); // Ожидаем: 1000
    }
}
